import { compose, pad, upscale, type Layer } from '../compose';
import type { Grid, SpriteSheet } from '../grid';

/**
 * Kodo (SPEC 4.4, 6.2). Authored at 68 x 62 art pixels, facing left, upscaled 2x to
 * 136 x 124. Huge hump-backed beast: forward-curving horn with negative space over the
 * face, small eye, open mouth line, neck fold, pillar legs, tapering tail. Stunned = kneels.
 */
const W = 68;
const H = 62;

const at = (rows: Grid, x: number, y: number): Layer => ({ rows, x, y });
const cut = (rows: Grid, x: number, y: number): Layer => ({ rows, x, y, mode: 'cut' });
const frame = (layers: readonly Layer[]): string[] => upscale(compose(W, H, layers), 2);
const rows = (row: string, n: number): string[] => Array<string>(n).fill(row);

/** Horn, head, hump, tail, and leg stubs (rows 0-45). */
const BODY: Grid = pad(W, [
  '',
  '',
  '',
  '',
  '..............................#########',
  '...........................################',
  '...##....................#####################',
  '...###.................#########################',
  '....###..............#############################',
  '.....###............################################',
  '......###..........###################################',
  '......####........#####################################',
  '.......####......#######################################',
  '.......#####....#########################################',
  '........#####..###########################################',
  '.....########.#############################################',
  '...#########################################################',
  '.############################################################',
  '#############################################################',
  '##############################################################',
  '##############################################################',
  '##############################################################',
  '################################################################',
  '#################################################################',
  '#################################################################',
  '##################################################################',
  '##################################################################',
  '#############################################################..####',
  '#############################################################...###',
  '#############################################################...###',
  '#############################################################....###',
  '...........#################################################.....###',
  '.###########################################################.....###',
  '..##########################################################......##',
  '...#########################################################......##',
  '....#######################################################.......##',
  '......#####################################################........#',
  '.........##################################################',
  '.............##############################################',
  '................###################......#################',
  '.................#################........################',
  '.................################..........###############',
  ...rows('.................###############...........###############', 4),
]);

const LEG_FWD: Grid = pad(11, [
  ...rows('....#######', 4),
  ...rows('...#######', 4),
  ...rows('..#######', 4),
  ...rows('.#######', 3),
  ...rows('##########', 3),
]);
const LEG_BACK: Grid = pad(11, [
  ...rows('#######', 4),
  ...rows('.#######', 4),
  ...rows('..#######', 4),
  ...rows('...#######', 3),
  ...rows('.##########', 3),
]);
const LEG_STRAIGHT: Grid = [...rows('..#######.', 15), ...rows('##########', 3)];
const LEG_LIFTED: Grid = [...rows('..#######.', 8), ...rows('##########', 3)];
const LEG_KNEEL: Grid = [...rows('..#######.', 6), ...rows('##########', 3)];
const FOLDED: Grid = pad(W, [
  '.............#####################........#################',
  '...........########################......###################',
  '..........##########################....#####################',
  '..........##########################....#####################',
]);

const EYE: Grid = ['##', '##'];
const SLIT: Grid = ['##'];
const NOSTRIL: Grid = ['#'];
const NECK_FOLD: Grid = rows('#', 15);

const body = (dy: number, dazed = false): Layer[] => [
  at(BODY, 0, dy),
  cut(NECK_FOLD, 17, 19 + dy),
  cut(NOSTRIL, 2, 20 + dy),
  dazed ? cut(SLIT, 7, 23 + dy) : cut(EYE, 7, 22 + dy),
];
const legs = (parts: readonly (readonly [Grid, number])[], y = 44): Layer[] =>
  parts.map(([g, x]) => at(g, x, y));

const walk = [
  frame([
    ...body(0),
    ...legs([
      [LEG_FWD, 13],
      [LEG_BACK, 25],
      [LEG_FWD, 39],
      [LEG_BACK, 51],
    ]),
  ]),
  frame([
    ...body(-1),
    ...legs([
      [LEG_STRAIGHT, 17],
      [LEG_LIFTED, 23],
      [LEG_STRAIGHT, 43],
      [LEG_LIFTED, 49],
    ]),
  ]),
  frame([
    ...body(0),
    ...legs([
      [LEG_FWD, 14],
      [LEG_BACK, 24],
      [LEG_FWD, 40],
      [LEG_BACK, 50],
    ]),
  ]),
  frame([
    ...body(-1),
    ...legs([
      [LEG_LIFTED, 15],
      [LEG_STRAIGHT, 23],
      [LEG_LIFTED, 41],
      [LEG_STRAIGHT, 49],
    ]),
  ]),
];

const kneel = [
  frame([
    ...body(7, true),
    ...legs(
      [
        [LEG_KNEEL, 15],
        [LEG_KNEEL, 23],
        [LEG_KNEEL, 41],
        [LEG_KNEEL, 49],
      ],
      53,
    ),
  ]),
  frame([...body(14, true), at(FOLDED, 0, 58)]),
];

export const kodoSheet: SpriteSheet = {
  id: 'kodo',
  frameWidth: 136,
  frameHeight: 124,
  animations: {
    walk: { fps: 5, frames: walk },
    kneel: { fps: 4, frames: kneel },
  },
};
