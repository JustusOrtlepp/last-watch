const idle = [0, 1, 2, 3].map((i) => {
  const bob = i < 2 ? 0 : 1;
  const swaying = i === 1 || i === 2;
  const layers: Layer[] = [
    at(UPPER, 0, bob),
    ...shoulderAxe(8, bob),
    swaying ? at(TAIL_SWAY, 8, 21 + bob) : at(TAIL_HANG, 9, 21 + bob),
    at(IDLE_LEGS, 0, 22),
  ];
  if (i === 3) layers.push(at(BLINK, 24, 7 + bob));
  return frame(layers);
});

const run = RUN_LEGS.map((legs, i) => {
  const bob = RUN_BOB[i]!;
  return frame([
    at(UPPER, 0, bob),
    ...shoulderAxe(8, bob),
    at(TAIL_RUN, 5, 20 + bob),
    at(legs, 0, 22),
  ]);
});

const jump = [JUMP_RISE_LEGS, JUMP_FALL_LEGS].map((legs) =>
  frame([at(UPPER, 0, 0), ...shoulderAxe(8, 0), at(TAIL_RUN, 5, 20), at(legs, 0, 22)]),
);

const stomp = STOMP_POSES.map(({ bob, legs }) =>
  frame([at(UPPER, 0, bob), ...shoulderAxe(8, bob), at(TAIL_HANG, 9, 21 + bob), at(legs, 0, 22)]),
);

const charge = CHARGE_LEGS.map((legs, i) =>
  // The back sits 2 left / 2 up in CHARGE_UPPER versus UPPER; the axe keeps its grip on it.
  frame([
    at(CHARGE_UPPER, 0, 6 + i),
    ...shoulderAxe(6, 2 + i),
    at(TAIL_RUN, 2, 19 + i),
    at(legs, 0, 22),
  ]),
);

